def parse(path):
    log = open(path, encoding='utf-8', errors='replace').read()
    red = set(m.group(1) for m in re.finditer(r'^(?:FAIL|ERROR): (\w+ \([\w.]+\))', log, re.M))
    names = set(re.findall(r'^(\w+ \([\w.]+\))', log, re.M))
    return red, names


def main():
    sqlite_red, sqlite_all = parse(sys.argv[1])
    mysql_red, mysql_all = parse(sys.argv[2])
    print('| ID | Группа | Серьёзность | Где | Находка | Красных тестов (SQLite / MySQL) | Рекомендация | Трудоёмкость |')
    print('|---|---|---|---|---|---|---|---|')
    totals = {}
    for fid, group, sev, where, summary, rx, rec, effort in FINDINGS:
        pattern = re.compile(rx)
        s = sorted(t for t in sqlite_red if pattern.search(t))
        m = sorted(t for t in mysql_red if pattern.search(t))
        totals[sev] = totals.get(sev, 0) + 1
        sample = ', '.join(x.split(' ')[0] for x in (s or m)[:2])
        evidence = f'{len(s)} / {len(m)}' + (f' (напр. `{sample}`)' if sample else '')
        print(f'| {fid} | {group} | {sev} | {where} | {summary} | {evidence} | {rec} | {effort} |')
